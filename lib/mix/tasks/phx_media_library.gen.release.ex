defmodule Mix.Tasks.PhxMediaLibrary.Gen.Release do
  @moduledoc """
  Generates the files that run the media doctor in a release, where there
  is no `mix`, the way `mix phx.gen.release` provides `bin/migrate`:

    * `lib/my_app/media_release.ex`: starts the library and your Repo, and
      runs `PhxMediaLibrary.Doctor.CLI`
    * `rel/overlays/bin/media_doctor`: runs it with the flags of
      `mix phx_media_library.doctor`

  ## Usage

      $ mix phx_media_library.gen.release

  Then, in the release:

      $ bin/media_doctor
      $ bin/media_doctor --regenerate --yes
      $ bin/media_doctor --id 8f2c4d1e-... --deep

  The script calls `bin/my_app`, named after your app; if your release has
  another name, edit the script. Existing files are not overwritten without
  asking.
  """

  @shortdoc "Generates bin/media_doctor for releases"

  use Mix.Task

  import Mix.Generator

  @impl Mix.Task
  def run(_args) do
    app = Mix.Project.config()[:app]
    module = app |> to_string() |> Macro.camelize() |> Kernel.<>(".MediaRelease")
    assigns = [app: app, module: module]

    create_file("lib/#{app}/media_release.ex", module_template(assigns))
    script = "rel/overlays/bin/media_doctor"

    if create_file(script, script_template(assigns)), do: File.chmod!(script, 0o755)

    Mix.shell().info("""

    Run the doctor in a release with the flags of
    `mix phx_media_library.doctor`:

        bin/media_doctor
        bin/media_doctor --regenerate --yes
    """)
  end

  embed_template(:module, """
  defmodule <%= @module %> do
    @moduledoc \"\"\"
    Runs PhxMediaLibrary's doctor in a release, where there is no `mix`:

        bin/media_doctor --regenerate --yes

    It takes the flags of `mix phx_media_library.doctor`. Generated by
    `mix phx_media_library.gen.release`.
    \"\"\"

    @doc "Check and repair media, then exit with the doctor's status."
    def doctor(argv \\\\ System.argv()) do
      # Start the library and the Repo only: not your web server or job queues.
      {:ok, _} = Application.ensure_all_started(:phx_media_library)
      repo = Application.fetch_env!(:phx_media_library, :repo)

      {:ok, status, _apps} =
        Ecto.Migrator.with_repo(repo, fn _repo -> PhxMediaLibrary.Doctor.CLI.main(argv) end)

      System.halt(status)
    end
  end
  """)

  embed_template(:script, """
  #!/bin/sh
  set -eu

  cd -P -- "$(dirname -- "$0")"
  exec ./<%= @app %> eval "<%= @module %>.doctor()" "$@"
  """)
end
